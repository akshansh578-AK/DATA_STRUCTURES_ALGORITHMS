package Basics;

public class Loops {
    static void main(String[] args) {
        // Loops are used for repititive task

        int i = 1; // Initialization
        while(i<9){ // condition
            System.out.println(i);
            i++; // increment
        }
        System.out.println("Done");

        for(int j = 0 ; j<8 ;j++){
            System.out.println(j);
        }
    }
}
