package Basics;

public class Conditionals2 {
    static void main(String[] args) {
        int n1 = 4 ;
        int n2 = 3;

        if(n1==n2){
            System.out.println("Both are equal");
        }
        else if (n1>n2) {
            System.out.println(n1+" is greater");
        }
        else{
            System.out.println(n2+" is greater");
        }
    }
}
